"""
Generates XrNative.g.cs (raw OpenXR bindings) from the official Khronos headers.

Only the types and functions listed in bindings.txt are emitted, so the surface stays small and auditable.
Usage:
    python3 generate.py <path to dir containing openxr.h and openxr_platform.h>

Headers: https://github.com/KhronosGroup/OpenXR-SDK/tree/release-<version>/include/openxr
Use the same release as the Android loader (org.khronos.openxr:openxr_loader_for_android) shipped by the Quest build.
"""

import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))

PRIMITIVES = {
    'uint8_t': 'byte', 'int8_t': 'sbyte', 'char': 'byte',
    'uint16_t': 'ushort', 'int16_t': 'short',
    'uint32_t': 'uint', 'int32_t': 'int',
    'uint64_t': 'ulong', 'int64_t': 'long',
    'float': 'float', 'double': 'double',
    'size_t': 'nuint',
    'XrBool32': 'uint', 'XrTime': 'long', 'XrDuration': 'long', 'XrVersion': 'ulong', 'XrFlags64': 'ulong',
    # Opaque platform types are passed through as pointers.
    'EGLDisplay': 'nint', 'EGLConfig': 'nint', 'EGLContext': 'nint', 'jobject': 'nint',
    'PFN_xrEglGetProcAddressMNDX': 'nint',
}

# Struct typedef aliases (e.g. "typedef XrUuid XrUuidEXT;"), bound as the aliased struct.
ALIASES = {
    'XrUuidEXT': 'XrUuid',
}


def read(path):
    with open(path, encoding='utf-8') as f:
        return f.read()


def parse_selection():
    sel = {'enum': [], 'flags': [], 'struct': [], 'function': []}
    for line in read(os.path.join(HERE, 'bindings.txt')).splitlines():
        line = line.split('#', 1)[0].strip()
        if not line:
            continue
        kind, name = line.split()
        sel[kind].append(name)
    return sel


def main(header_dir):
    src = read(os.path.join(header_dir, 'openxr.h')) + '\n' + read(os.path.join(header_dir, 'openxr_platform.h'))
    version = re.search(r'#define XR_CURRENT_API_VERSION XR_MAKE_VERSION\((\d+), (\d+), (\d+)\)', src).groups()

    handles = set(re.findall(r'^XR_DEFINE_HANDLE\((\w+)\)', src, re.M))
    atoms = set(re.findall(r'^XR_DEFINE_ATOM\((\w+)\)', src, re.M))
    flag_types = set(re.findall(r'^typedef XrFlags64 (\w+);', src, re.M))
    enum_types = set(re.findall(r'^typedef enum (\w+) \{', src, re.M))
    defines = dict(re.findall(r'^#define (XR_\w+)\s+(\d+)U?\s*$', src, re.M))

    sel = parse_selection()
    selected_structs = set(sel['struct'])
    out = []
    w = out.append

    def map_type(ctype, for_field):
        ctype = ctype.replace('XR_MAY_ALIAS', '').replace('const', '').replace('struct ', '').strip()
        ptr = ctype.count('*')
        base = ctype.replace('*', '').strip()
        base = ALIASES.get(base, base)

        if base in PRIMITIVES:
            cs = PRIMITIVES[base]
        elif base in handles or base in atoms or base in flag_types:
            cs = 'ulong'
        elif base in enum_types:
            cs = base
        elif base == 'void':
            cs = 'void'
        elif base in selected_structs:
            cs = base
        elif ptr > 0:
            # Pointer to a struct we don't bind (e.g. struct timespec): opaque pointer.
            cs = 'void'
        else:
            raise SystemExit(f'Unmapped type "{base}" (add it to bindings.txt or PRIMITIVES)')

        return cs + '*' * ptr

    w('// <auto-generated />')
    w(f'// Generated by generate.py from OpenXR {".".join(version)} headers. Do not edit by hand.')
    w('')
    w('#pragma warning disable IDE1006, CS0649')
    w('')
    w('using System.Runtime.InteropServices;')
    w('')
    w('namespace osu.Framework.Platform.OpenXR.Native')
    w('{')
    w('    public static class XrConstants')
    w('    {')
    w(f'        public const ulong XR_CURRENT_API_VERSION = ({version[0]}UL << 48) | ({version[1]}UL << 32) | {version[2]}UL;')
    w(f'        public const ulong XR_API_VERSION_1_0 = (1UL << 48) | (0UL << 32) | {version[2]}UL;')
    for name, value in sorted(defines.items()):
        if name.startswith('XR_MAX_') or name in ('XR_NULL_PATH', 'XR_NULL_SYSTEM_ID', 'XR_NO_DURATION', 'XR_INFINITE_DURATION', 'XR_UUID_SIZE'):
            w(f'        public const uint {name} = {value};')
    w('        public const long XR_INFINITE_DURATION = 0x7fffffffffffffffL;')
    w('    }')

    # Enums.
    for name in sel['enum']:
        m = re.search(r'^typedef enum ' + name + r' \{\n(.*?)\n\} ' + name + ';', src, re.M | re.S)
        if not m:
            raise SystemExit(f'enum {name} not found')
        w('')
        w(f'    public enum {name}')
        w('    {')
        for line in m.group(1).splitlines():
            line = line.strip().rstrip(',')
            if not line or line.startswith('//'):
                continue
            key, value = [p.strip() for p in line.split('=', 1)]
            if key.endswith('_MAX_ENUM'):
                continue
            w(f'        {key} = {value},')
        w('    }')

    # Flag constants.
    for name in sel['flags']:
        if name not in flag_types:
            raise SystemExit(f'flags {name} not found')
        values = re.findall(r'^static const ' + name + r' (\w+) = (0x[0-9A-Fa-f]+);', src, re.M)
        w('')
        w(f'    public static class {name}')
        w('    {')
        for key, value in values:
            w(f'        public const ulong {key} = {value};')
        w('    }')

    # Structs.
    for name in sel['struct']:
        m = re.search(r'^typedef struct (?:XR_MAY_ALIAS )?' + name + r' \{\n(.*?)\n\} ' + name + ';', src, re.M | re.S)
        if not m:
            raise SystemExit(f'struct {name} not found')
        w('')
        w('    [StructLayout(LayoutKind.Sequential)]')
        w(f'    public unsafe struct {name}')
        w('    {')
        for line in m.group(1).splitlines():
            line = line.strip().rstrip(';')
            if not line:
                continue
            arr = re.match(r'(.*?)(\w+)\[(\w+)\]$', line)
            if arr:
                ctype, field, size = arr.group(1).strip(), arr.group(2), arr.group(3)
                cs = map_type(ctype, True)
                if cs not in ('byte', 'sbyte', 'ushort', 'short', 'uint', 'int', 'ulong', 'long', 'float', 'double'):
                    raise SystemExit(f'fixed array of non-primitive in {name}.{field}')
                count = size if size.isdigit() else f'(int)XrConstants.{size}'
                w(f'        public fixed {cs} {field}[{count}];')
                continue
            fm = re.match(r'(.*?[\s\*])(\w+)$', line)
            ctype, field = fm.group(1).strip(), fm.group(2)
            w(f'        public {map_type(ctype, True)} {field};')
        w('    }')

    # Function table, resolved through xrGetInstanceProcAddr.
    def signature(name):
        m = re.search(r'typedef XrResult \(XRAPI_PTR \*PFN_' + name + r'\)\((.*?)\);', src, re.S)
        if not m:
            raise SystemExit(f'function {name} not found')
        params = [p.strip() for p in m.group(1).replace('\n', ' ').split(',') if p.strip() and p.strip() != 'void']
        # Array parameters (e.g. "char buffer[XR_MAX_RESULT_STRING_SIZE]") decay to pointers in C.
        params = [re.sub(r'(\w+)\[\w+\]$', r'* \1', p) for p in params]
        types = [map_type(re.match(r'(.*?[\s\*])(\w+)$', p).group(1).strip(), False) for p in params]
        return f'delegate* unmanaged<{", ".join(types + ["XrResult"])}>'

    w('')
    w('    public unsafe partial class XrFunctions')
    w('    {')
    for name in sel['function']:
        w(f'        public {signature(name)} {name};')
    w('')
    w('        /// <summary>')
    w('        /// Resolves every function in this table. Functions that can\'t be resolved for <paramref name="instance"/>')
    w('        /// (e.g. extension functions whose extension wasn\'t enabled) are left null.')
    w('        /// </summary>')
    w('        public void Load(ulong instance)')
    w('        {')
    for name in sel['function']:
        w(f'            {name} = ({signature(name)})Resolve(instance, "{name}");')
    w('        }')
    w('    }')
    w('}')

    with open(os.path.join(HERE, 'XrNative.g.cs'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(out) + '\n')

    print(f'Wrote XrNative.g.cs: {len(sel["enum"])} enums, {len(sel["flags"])} flag groups, '
          f'{len(sel["struct"])} structs, {len(sel["function"])} functions (OpenXR {".".join(version)})')


if __name__ == '__main__':
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    main(sys.argv[1])
